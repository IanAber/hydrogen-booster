let currentLang = 'en';

function t(key) {
  const dict = I18N[currentLang] || I18N.en;
  return dict[key] || I18N.en[key] || key;
}

// translateMessage renders a backend Message ({code, params, text} -
// see messages.go) in the current language: the "msg_<code>" template
// with its {placeholders} filled from params - a "sensor" param is a
// sensor name, translated via "sensor_<name>"; an object param is a
// nested Message, translated recursively; anything else is shown as
// is. Falls back to the message's own English text when its code has
// no template (e.g. a raw driver error).
function translateMessage(m, nested) {
  if (!m) return '';
  if (typeof m === 'string') return m;
  const key = 'msg_' + m.code;
  if (!m.code || !(I18N.en[key])) return m.text || '';
  const params = m.params || {};
  const out = t(key).replace(/\{(\w+)\}/g, (_, name) => {
    const v = params[name];
    if (v === undefined || v === null) return '';
    if (typeof v === 'object') return translateMessage(v, true);
    if (name === 'sensor') return I18N.en['sensor_' + v] ? t('sensor_' + v) : v;
    return String(v);
  });
  return nested ? out : out.charAt(0).toUpperCase() + out.slice(1);
}

// responseErrorText is a failed API response's error in the current
// language - from its X-Message header when the backend sent one (see
// writeError in messages.go), else the plain-text body as before.
async function responseErrorText(res) {
  const body = await res.text();
  const header = res.headers.get('X-Message');
  if (header) {
    try { return translateMessage(JSON.parse(decodeURIComponent(header))); } catch (e) { /* fall through */ }
  }
  return body;
}

// faultMessages lists a status poll's faults in the current language,
// using faultDetails when present (falling back to the plain English
// faults list, minus timestamps, from an older backend).
function faultMessages(s) {
  if (s.faultDetails && s.faultDetails.length) return s.faultDetails.map(f => translateMessage(f));
  return (s.faults || []).map(f => f.replace(/^\[[^\]]*\]\s*/, ''));
}

function applyTranslations() {
  document.documentElement.lang = currentLang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
}

// setLanguage lets a page (admin.html) preview a language instantly,
// before it's been Applied/persisted server-side.
function setLanguage(lang) {
  currentLang = I18N[lang] ? lang : 'en';
  applyTranslations();
}

// initI18n reads the current language (and banner title) from the
// server once, applies translations and the banner, and returns the
// fetched config (or null on failure) so the caller can reuse it rather
// than issuing a second /api/config request.
async function initI18n() {
  let config = null;
  try {
    const res = await fetch('/api/config');
    const resp = await res.json();
    config = resp.config;
    currentLang = (config && I18N[config.language]) ? config.language : 'en';
  } catch (e) {
    currentLang = 'en';
  }
  applyTranslations();
  const bannerEl = document.getElementById('bannerTitle');
  if (bannerEl && config && config.systemName) bannerEl.textContent = config.systemName;
  return config;
}
